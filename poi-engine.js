// --- HARMONIC GEOMETRY FLOW MORPH ENGINE (DUAL-EQUATION SYNTHESIZER) ---
function generateMorphedPattern(destCanvas, modelA, modelB, flowStyle, morphRatio, params, colSampler) {
    const w = destCanvas.width;
    const h = destCanvas.height;

    const genA = POI_GENERATORS[modelA] || POI_GENERATORS.neg_void_blackhole;
    const genB = POI_GENERATORS[modelB] || POI_GENERATORS.illusion_fraser_spiral;

    const canvasA = document.createElement('canvas'); canvasA.width = w; canvasA.height = h;
    const canvasB = document.createElement('canvas'); canvasB.width = w; canvasB.height = h;

    genA(canvasA.getContext('2d'), w, h, params, colSampler);
    genB(canvasB.getContext('2d'), w, h, params, colSampler);

    const ctx = destCanvas.getContext('2d');
    ctx.clearRect(0, 0, w, h);

    const dataA = canvasA.getContext('2d').getImageData(0, 0, w, h).data;
    const dataB = canvasB.getContext('2d').getImageData(0, 0, w, h).data;
    const outImg = ctx.createImageData(w, h);
    const outD = outImg.data;

    for (let x = 0; x < w; x++) {
        const normX = x / w;
        for (let y = 0; y < h; y++) {
            const idx = (y * w + x) * 4;

            let t = morphRatio;
            if (flowStyle === 'azimuthal_flow') {
                // A -> B -> A continuous seamless loop across azimuth 0° -> 180° -> 360°
                const cycle = (1 - Math.cos(normX * Math.PI * 2)) * 0.5;
                t = cycle * morphRatio;
            } else if (flowStyle === 'interlaced_rails') {
                // Alternating LED pixel rows
                t = (y % 2 === 0) ? (1 - morphRatio) : morphRatio;
            } else if (flowStyle === 'nonlinear_phase') {
                // Non-linear spatial phase modulation
                const wave = Math.sin(normX * Math.PI * 4 + (y / h) * Math.PI * 2);
                t = Math.max(0, Math.min(1, morphRatio + wave * 0.35));
            }

            outD[idx] = dataA[idx] * (1 - t) + dataB[idx] * t;
            outD[idx + 1] = dataA[idx + 1] * (1 - t) + dataB[idx + 1] * t;
            outD[idx + 2] = dataA[idx + 2] * (1 - t) + dataB[idx + 2] * t;
            outD[idx + 3] = Math.max(dataA[idx + 3], dataB[idx + 3]);
        }
    }
    ctx.putImageData(outImg, 0, 0);
}

// --- UNIVERSAL ZERO-SEAM CONTINUITY GUARDIAN ---
function applyPerfectSeamGuardian(canvas, blendWidth = 6) {
    const w = canvas.width;
    const h = canvas.height;
    if (w < blendWidth * 2) return;
    const ctx = canvas.getContext('2d');
    const imgData = ctx.getImageData(0, 0, w, h);
    const data = imgData.data;

    for (let y = 0; y < h; y++) {
        const left0 = (y * w + 0) * 4;
        const rightEnd = (y * w + (w - 1)) * 4;

        if (data[left0] !== data[rightEnd] || data[left0+1] !== data[rightEnd+1] || data[left0+2] !== data[rightEnd+2]) {
            for (let bx = 0; bx < blendWidth; bx++) {
                const leftX = bx;
                const rightX = w - blendWidth + bx;
                const leftIdx = (y * w + leftX) * 4;
                const rightIdx = (y * w + rightX) * 4;

                const t = (1 - Math.cos(((bx + 0.5) / blendWidth) * Math.PI)) * 0.5;
                const avgR = data[leftIdx] * (1 - t) + data[rightIdx] * t;
                const avgG = data[leftIdx + 1] * (1 - t) + data[rightIdx + 1] * t;
                const avgB = data[leftIdx + 2] * (1 - t) + data[rightIdx + 2] * t;
                const avgA = Math.max(data[leftIdx + 3], data[rightIdx + 3]);

                data[leftIdx] = avgR; data[leftIdx + 1] = avgG; data[leftIdx + 2] = avgB; data[leftIdx + 3] = avgA;
                data[rightIdx] = avgR; data[rightIdx + 1] = avgG; data[rightIdx + 2] = avgB; data[rightIdx + 3] = avgA;
            }
        }
    }
    ctx.putImageData(imgData, 0, 0);
}

// --- MULTI-PATTERN SEQUENCE JOINER ---
function joinPatternSequence(canvases, options = {}) {
    if (!canvases || canvases.length === 0) return null;
    const h = canvases[0].height;
    const transition = options.transition || 'crossfade';
    const overlap = Math.max(0, parseInt(options.overlap || 24));
    const isSeamlessLoop = !!options.seamlessLoop;

    if (canvases.length === 1 && !isSeamlessLoop) {
        const out = document.createElement('canvas');
        out.width = canvases[0].width; out.height = h;
        out.getContext('2d').drawImage(canvases[0], 0, 0);
        return out;
    }

    let totalW = 0;
    canvases.forEach((c, idx) => {
        totalW += c.width;
        if (idx > 0 && transition !== 'none') totalW -= overlap;
    });

    if (totalW * h > 40000) totalW = Math.floor(40000 / h);

    const outCanvas = document.createElement('canvas');
    outCanvas.width = Math.max(1, totalW);
    outCanvas.height = h;
    const ctx = outCanvas.getContext('2d');

    let currentX = 0;
    for (let i = 0; i < canvases.length; i++) {
        const img = canvases[i];
        if (i === 0 || transition === 'none' || overlap === 0) {
            ctx.drawImage(img, currentX, 0);
            currentX += img.width;
        } else {
            const prevX = currentX - overlap;
            const blendW = overlap;
            ctx.drawImage(img, blendW, 0, img.width - blendW, h, currentX, 0, img.width - blendW, h);

            const tempA = document.createElement('canvas');
            tempA.width = blendW; tempA.height = h;
            tempA.getContext('2d').drawImage(outCanvas, prevX, 0, blendW, h, 0, 0, blendW, h);

            const tempB = document.createElement('canvas');
            tempB.width = blendW; tempB.height = h;
            tempB.getContext('2d').drawImage(img, 0, 0, blendW, h, 0, 0, blendW, h);

            const blendZone = ctx.createImageData(blendW, h);
            const dataA = tempA.getContext('2d').getImageData(0, 0, blendW, h).data;
            const dataB = tempB.getContext('2d').getImageData(0, 0, blendW, h).data;
            const outD = blendZone.data;

            for (let bx = 0; bx < blendW; bx++) {
                const t = (1 - Math.cos((bx / blendW) * Math.PI)) * 0.5;
                for (let by = 0; by < h; by++) {
                    const idx = (by * blendW + bx) * 4;
                    if (transition === 'crossfade') {
                        outD[idx] = dataA[idx] * (1 - t) + dataB[idx] * t;
                        outD[idx + 1] = dataA[idx + 1] * (1 - t) + dataB[idx + 1] * t;
                        outD[idx + 2] = dataA[idx + 2] * (1 - t) + dataB[idx + 2] * t;
                        outD[idx + 3] = Math.max(dataA[idx + 3], dataB[idx + 3]);
                    } else if (transition === 'black') {
                        const dip = Math.sin((bx / blendW) * Math.PI);
                        const bright = 1 - dip;
                        const src = t < 0.5 ? dataA : dataB;
                        outD[idx] = src[idx] * bright;
                        outD[idx + 1] = src[idx + 1] * bright;
                        outD[idx + 2] = src[idx + 2] * bright;
                        outD[idx + 3] = src[idx + 3];
                    } else if (transition === 'strobe') {
                        const isStrobeWhite = (bx % 4 < 2);
                        if (isStrobeWhite) {
                            outD[idx] = 255; outD[idx + 1] = 255; outD[idx + 2] = 255; outD[idx + 3] = 255;
                        } else {
                            const src = t < 0.5 ? dataA : dataB;
                            outD[idx] = src[idx]; outD[idx + 1] = src[idx + 1]; outD[idx + 2] = src[idx + 2]; outD[idx + 3] = src[idx + 3];
                        }
                    }
                }
            }
            ctx.putImageData(blendZone, prevX, 0);
            currentX += (img.width - overlap);
        }
    }

    if (isSeamlessLoop && overlap > 0 && outCanvas.width > overlap * 2) {
        const w = outCanvas.width;
        const head = ctx.getImageData(0, 0, overlap, h);
        const tail = ctx.getImageData(w - overlap, 0, overlap, h);
        const headD = head.data;
        const tailD = tail.data;

        for (let bx = 0; bx < overlap; bx++) {
            const t = (1 - Math.cos((bx / overlap) * Math.PI)) * 0.5;
            for (let by = 0; by < h; by++) {
                const idx = (by * overlap + bx) * 4;
                const r = tailD[idx] * (1 - t) + headD[idx] * t;
                const g = tailD[idx + 1] * (1 - t) + headD[idx + 1] * t;
                const b = tailD[idx + 2] * (1 - t) + headD[idx + 2] * t;
                headD[idx] = r; headD[idx + 1] = g; headD[idx + 2] = b;
                tailD[idx] = r; tailD[idx + 1] = g; tailD[idx + 2] = b;
            }
        }
        ctx.putImageData(head, 0, 0);
        ctx.putImageData(tail, w - overlap, 0);
    }

    applyPerfectSeamGuardian(outCanvas, 8);
    return outCanvas;
}

// --- VERIFY SEAM CONTINUITY MATH ---
function checkSeamContinuity(canvas) {
    const w = canvas.width;
    const h = canvas.height;
    const ctx = canvas.getContext('2d');
    const dLeft = ctx.getImageData(0, 0, 1, h).data;
    const dRight = ctx.getImageData(w - 1, 0, 1, h).data;

    let totalDiff = 0;
    for (let y = 0; y < h; y++) {
        const idx = y * 4;
        const dr = Math.abs(dLeft[idx] - dRight[idx]);
        const dg = Math.abs(dLeft[idx + 1] - dRight[idx + 1]);
        const db = Math.abs(dLeft[idx + 2] - dRight[idx + 2]);
        totalDiff += (dr + dg + db);
    }

    const maxDiff = h * 255 * 3;
    const continuityPct = Math.max(0, 100 - (totalDiff / maxDiff) * 100);
    return {
        isSeamless: totalDiff < (h * 5),
        continuity: continuityPct.toFixed(2),
        totalDiff: totalDiff
    };
}

function applyMandalaMode(srcCanvas, segments = 8) {
    const w = srcCanvas.width;
    const h = srcCanvas.height;
    const tempCanvas = document.createElement('canvas');
    tempCanvas.width = w; tempCanvas.height = h;
    tempCanvas.getContext('2d').drawImage(srcCanvas, 0, 0);

    const outCtx = srcCanvas.getContext('2d');
    outCtx.clearRect(0, 0, w, h);

    const segW = w / segments;
    for (let s = 0; s < segments; s++) {
        outCtx.save();
        if (s % 2 === 1) {
            outCtx.translate((s + 1) * segW, 0);
            outCtx.scale(-1, 1);
            outCtx.drawImage(tempCanvas, 0, 0, segW, h, 0, 0, segW, h);
        } else {
            outCtx.drawImage(tempCanvas, 0, 0, segW, h, s * segW, 0, segW, h);
        }
        outCtx.restore();
    }
}

function applyMultiSymmetry(canvas, { mirrorH, mirrorV, kaleido }) {
    if (!mirrorH && !mirrorV && (!kaleido || kaleido === 0)) return;
    const w = canvas.width;
    const h = canvas.height;
    const temp = document.createElement('canvas');
    temp.width = w; temp.height = h;
    temp.getContext('2d').drawImage(canvas, 0, 0);

    const ctx = canvas.getContext('2d');

    if (mirrorH) {
        ctx.save();
        ctx.clearRect(w / 2, 0, w / 2, h);
        ctx.translate(w, 0);
        ctx.scale(-1, 1);
        ctx.drawImage(temp, 0, 0, w / 2, h, 0, 0, w / 2, h);
        ctx.restore();
        temp.getContext('2d').clearRect(0, 0, w, h);
        temp.getContext('2d').drawImage(canvas, 0, 0);
    }

    if (mirrorV) {
        ctx.save();
        ctx.clearRect(0, h / 2, w, h / 2);
        ctx.translate(0, h);
        ctx.scale(1, -1);
        ctx.drawImage(temp, 0, 0, w, h / 2, 0, 0, w / 2, h);
        ctx.restore();
    }

    if (kaleido && kaleido >= 4) applyMandalaMode(canvas, kaleido);
}

function applyPostFX(canvas, fx) {
    if (!fx) return;
    const w = canvas.width;
    const h = canvas.height;
    const ctx = canvas.getContext('2d');

    const imgData = ctx.getImageData(0, 0, w, h);
    const data = imgData.data;
    const srcCopy = new Uint8ClampedArray(data);

    const hasStrobe = fx.strobe > 0;
    const hasRGB = fx.rgb > 0;
    const hasWave = fx.wave > 0;
    const hasGlow = fx.glow > 0;

    if (!hasStrobe && !hasRGB && !hasWave && !hasGlow) return;

    for (let x = 0; x < w; x++) {
        const isStrobed = hasStrobe && ((x % (fx.strobe * 2)) < fx.strobe);
        for (let y = 0; y < h; y++) {
            const destIdx = (y * w + x) * 4;
            if (isStrobed) {
                data[destIdx] = 0; data[destIdx + 1] = 0; data[destIdx + 2] = 0; data[destIdx + 3] = 0;
                continue;
            }

            let sampleX = x;
            let sampleY = y;
            if (hasWave) {
                const waveOff = Math.sin((x / w) * Math.PI * 2 * 2) * fx.wave;
                sampleY = Math.max(0, Math.min(h - 1, Math.round(y + waveOff)));
            }

            sampleX = ((sampleX % w) + w) % w;
            const srcIdx = (sampleY * w + sampleX) * 4;

            if (hasRGB) {
                const rx = ((sampleX + fx.rgb) % w + w) % w;
                const bx = ((sampleX - fx.rgb) % w + w) % w;
                data[destIdx] = srcCopy[(sampleY * w + rx) * 4];
                data[destIdx + 1] = srcCopy[srcIdx + 1];
                data[destIdx + 2] = srcCopy[(sampleY * w + bx) * 4 + 2];
                data[destIdx + 3] = 255;
            } else {
                data[destIdx] = srcCopy[srcIdx];
                data[destIdx + 1] = srcCopy[srcIdx + 1];
                data[destIdx + 2] = srcCopy[srcIdx + 2];
                data[destIdx + 3] = srcCopy[srcIdx + 3];
            }
        }
    }
    ctx.putImageData(imgData, 0, 0);

    if (hasGlow) {
        ctx.save();
        ctx.globalCompositeOperation = 'lighter';
        ctx.filter = `blur(${fx.glow * 0.5}px)`;
        ctx.drawImage(canvas, 0, 0);
        ctx.restore();
    }
}

function shiftCanvasPhase(canvas, deltaX) {
    const w = canvas.width;
    const h = canvas.height;
    const shift = ((Math.round(deltaX) % w) + w) % w;
    if (shift === 0) return canvas;

    const out = document.createElement('canvas');
    out.width = w; out.height = h;
    const ctx = out.getContext('2d');
    ctx.drawImage(canvas, shift, 0, w - shift, h, 0, 0, w - shift, h);
    ctx.drawImage(canvas, 0, 0, shift, h, w - shift, 0, shift, h);
    return out;
}

function canvasToBmpBlob(canvas, options = {}) {
    const w = canvas.width;
    const h = canvas.height;
    const ctx = canvas.getContext('2d');
    const imgData = ctx.getImageData(0, 0, w, h);
    const data = imgData.data;

    const rowSize = Math.floor((24 * w + 31) / 32) * 4;
    const pixelArraySize = rowSize * h;
    const fileSize = 54 + pixelArraySize;

    const buffer = new ArrayBuffer(fileSize);
    const view = new DataView(buffer);

    view.setUint8(0, 0x42); // 'B'
    view.setUint8(1, 0x4D); // 'M'
    view.setUint32(2, fileSize, true);
    view.setUint16(6, 0, true);
    view.setUint16(8, 0, true);
    view.setUint32(10, 54, true);

    view.setUint32(14, 40, true);
    view.setInt32(18, w, true);
    view.setInt32(22, options.topDown ? -h : h, true);
    view.setUint16(26, 1, true);
    view.setUint16(28, 24, true);
    view.setUint32(30, 0, true);
    view.setUint32(34, pixelArraySize, true);
    view.setInt32(38, 2835, true);
    view.setInt32(42, 2835, true);
    view.setUint32(46, 0, true);
    view.setUint32(50, 0, true);

    let offset = 54;
    for (let y = 0; y < h; y++) {
        const srcY = options.topDown ? y : (h - 1 - y);
        let rowOffset = offset;
        for (let x = 0; x < w; x++) {
            const srcIdx = (srcY * w + x) * 4;
            view.setUint8(rowOffset, data[srcIdx + 2]);     // B
            view.setUint8(rowOffset + 1, data[srcIdx + 1]); // G
            view.setUint8(rowOffset + 2, data[srcIdx]);     // R
            rowOffset += 3;
        }
        for (let p = w * 3; p < rowSize; p++) {
            view.setUint8(rowOffset++, 0);
        }
        offset += rowSize;
    }

    return new Blob([buffer], { type: 'image/bmp' });
}

