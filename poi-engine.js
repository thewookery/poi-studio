function samplePalette(colors, t, mode = 'cyclic') {
    t = ((t % 1) + 1) % 1;
    const n = colors.length;
    if (n === 0) return '#00adb5';
    if (n === 1) return colors[0];

    let p, c1, c2;
    if (mode === 'pingpong') {
        const pingT = 1.0 - Math.abs(2.0 * t - 1.0);
        p = pingT * (n - 1);
        const i = Math.floor(p);
        const f = p - i;
        c1 = hexToRgb(colors[i]);
        c2 = hexToRgb(colors[Math.min(n - 1, i + 1)]);
        return rgbToHex(c1.r + (c2.r - c1.r) * f, c1.g + (c2.g - c1.g) * f, c1.b + (c2.b - c1.b) * f);
    } else {
        p = t * n;
        const i = Math.floor(p) % n;
        const nextI = (i + 1) % n;
        const f = p - Math.floor(p);
        c1 = hexToRgb(colors[i]);
        c2 = hexToRgb(colors[nextI]);
        return rgbToHex(c1.r + (c2.r - c1.r) * f, c1.g + (c2.g - c1.g) * f, c1.b + (c2.b - c1.b) * f);
    }
}

function createColorSampler(paletteKey, direction, seamlessMode = 'cyclic') {
    const colors = getPaletteColors(paletteKey);
    return function(x, y, w, h, offset = 0) {
        let t = 0;
        const normX = ((x % w) + w) % w / w;
        const normY = Math.max(0, Math.min(1, y / h));

        switch (direction) {
            case 'h': t = normX; break;
            case 'h_rev': t = 1 - normX; break;
            case 'v': t = normY; break;
            case 'v_rev': t = 1 - normY; break;
            case 'diag': t = (normX + normY) * 0.5; break;
            case 'radial': t = normY; break;
            default: t = normX;
        }

        const isHorizontal = (direction === 'h' || direction === 'h_rev' || direction === 'diag');
        const effectiveMode = isHorizontal ? seamlessMode : 'linear';
        return samplePalette(colors, t + offset, effectiveMode);
    };
}

